async page => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setDeviceMetricsOverride', { width:1512, height:949, deviceScaleFactor:2, mobile:false });
  await page.getByRole('button', {name:'Editable.md',exact:true}).click();
  await page.getByRole('tabpanel', {name:'Note Editor'}).getByRole('heading', {name:'Editable',level:2,exact:true}).waitFor();
  // Initial fixture data only: an existing empty group. All bookmark actions below use UI.
  const setup = await page.evaluate(() => {
    const ids = [...new Set(Object.keys(localStorage).flatMap(key => key.match(/vault:[a-f0-9]{64}/gu) ?? []))];
    if (ids.length !== 1) throw Error('Expected one isolated fixture vault');
    const key = 'tocktutor.bookmarks.v1.' + ids[0];
    const seeded = JSON.stringify([{id:'pr-study',kind:'group',title:'Study',children:[]}]);
    const existing = localStorage.getItem(key);
    if (existing !== null && existing !== '[]' && existing !== seeded) throw Error('Expected empty fixture bookmarks');
    localStorage.setItem(key, seeded);
    return {key};
  });
  await page.reload();
  await page.getByRole('navigation',{name:'App Navigation'}).getByRole('button',{name:'TockCoder',exact:true}).click();
  await page.getByRole('button',{name:'Configure later',exact:true}).click();
  await page.getByRole('navigation',{name:'App Navigation'}).getByRole('button',{name:'TockTutor',exact:true}).click();
  const trigger = page.getByRole('button', {name:'More Note Actions',exact:true});
  await trigger.waitFor();
  await trigger.click();
  const menu = page.getByRole('menu');
  const labels = await menu.locator('[role^=menuitem]').allTextContents();
  const metrics = await menu.locator('[role^=menuitem]').evaluateAll(items => items.map(el => ({text:el.textContent.trim(),height:el.getBoundingClientRect().height})));
  if (metrics.some(row => Math.abs(row.height-24.9)>1)) throw Error('Menu row density differs from reference');
  await page.keyboard.press('Home');
  await page.waitForFunction(() => document.activeElement?.textContent?.trim() === 'Backlinks in Document');
  const first = await page.evaluate(() => document.activeElement?.textContent?.trim());
  if (first !== 'Backlinks in Document') throw Error('Home did not focus first menu item');
  await page.keyboard.press('End');
  await page.waitForFunction(() => document.activeElement?.textContent?.trim() === 'Move File to Trash');
  const last = await page.evaluate(() => document.activeElement?.textContent?.trim());
  if (last !== 'Move File to Trash') throw Error('End did not focus last menu item');
  const copy = page.getByRole('menuitem',{name:'Copy Path',exact:true});
  await copy.focus(); await page.keyboard.press('ArrowRight');
  await page.getByRole('menuitem',{name:'Copy Absolute Path',exact:true}).waitFor();
  const boxes = await page.getByRole('menu').evaluateAll(items=>items.map(el=>{const r=el.getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height,right:r.right,bottom:r.bottom};}));
  if(boxes.some(r=>r.x<0 || r.y<40 || r.right>1512 || r.bottom>949)) throw Error('Menu outside usable viewport');
  await page.screenshot({path:'/tmp/tutor-pr-menu-dark.png',scale:'device'});
  await page.keyboard.press('ArrowLeft');
  await page.getByRole('menuitem',{name:'Copy Absolute Path',exact:true}).waitFor({state:'detached'});
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='More Note Actions');
  await trigger.click();
  await page.getByRole('menuitem',{name:'Open Linked View',exact:true}).focus(); await page.keyboard.press('ArrowRight');
  for(const name of ['Backlinks','Outgoing Links','Properties','Outline','Local Graph']) await page.getByRole('menuitem',{name,exact:true}).last().waitFor();
  await page.keyboard.press('ArrowLeft');
  await page.getByRole('menuitem',{name:'Local Graph',exact:true}).waitFor({state:'detached'});
  await page.keyboard.press('Escape');
  await page.getByRole('menu').waitFor({state:'hidden'});
  await trigger.click(); await page.getByRole('menuitem',{name:'Bookmark Note…',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'Bookmark Note',exact:true});
  if(await dialog.getByRole('option',{name:'No Group',exact:true}).count()!==1) throw Error('Bookmark option not Title Case');
  await dialog.getByRole('textbox',{name:'Bookmark Title',exact:true}).fill('PR Original Bookmark');
  await dialog.getByRole('button',{name:'Save',exact:true}).click(); await dialog.waitFor({state:'hidden'});
  const created=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),setup.key);
  const original=created.find(record=>record.kind==='note');
  if(!original || original.path!=='Editable.md') throw Error('Bookmark did not target current note');
  await trigger.click(); await page.getByRole('menuitem',{name:'Edit Bookmark…',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Edit Bookmark',exact:true});
  await dialog.getByRole('textbox',{name:'Bookmark Title',exact:true}).fill('PR Edited Bookmark');
  await dialog.getByRole('combobox',{name:'Bookmark Group',exact:true}).selectOption('pr-study');
  await page.screenshot({path:'/tmp/tutor-pr-bookmark-dark.png',scale:'device'});
  await dialog.getByRole('button',{name:'Save',exact:true}).click(); await dialog.waitFor({state:'hidden'});
  const edited=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),setup.key);
  const children=edited.find(record=>record.id==='pr-study').children;
  if(children.length!==1 || children[0].id!==original.id || children[0].title!=='PR Edited Bookmark' || children[0].path!=='Editable.md' || edited.some(record=>record.kind==='note')) throw Error('Bookmark identity/group move failed');
  await trigger.click(); await page.getByRole('menuitem',{name:'Edit Bookmark…',exact:true}).click();
  await dialog.getByRole('textbox',{name:'Bookmark Title',exact:true}).fill('Discarded');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click(); await dialog.waitFor({state:'hidden'});
  const afterCancel=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),setup.key);
  if(JSON.stringify(afterCancel)!==JSON.stringify(edited)) throw Error('Cancel changed stored bookmark');
  const response=await page.reload(); if(response.status()!==200) throw Error('Bookmark reload failed');
  await page.getByRole('navigation',{name:'App Navigation'}).getByRole('button',{name:'TockCoder',exact:true}).click();
  await page.getByRole('button',{name:'Configure later',exact:true}).click();
  await page.getByRole('navigation',{name:'App Navigation'}).getByRole('button',{name:'TockTutor',exact:true}).click();
  await trigger.waitFor(); await trigger.click(); await page.getByRole('menuitem',{name:'Edit Bookmark…',exact:true}).click();
  if(await dialog.getByRole('textbox',{name:'Bookmark Title',exact:true}).inputValue()!=='PR Edited Bookmark' || await dialog.getByRole('combobox',{name:'Bookmark Group',exact:true}).inputValue()!=='pr-study') throw Error('Bookmark did not persist');
  await dialog.getByRole('button',{name:'Remove',exact:true}).click(); await dialog.waitFor({state:'hidden'});
  const removed=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),setup.key);
  if(removed.length!==1 || removed[0].id!=='pr-study' || removed[0].children.length!==0) throw Error('Remove changed unrelated group or retained note');
  const geometry=await page.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio,colorScheme:document.documentElement.style.colorScheme,skin:document.documentElement.dataset.tockteamSkin??null,bodySkin:document.body.dataset.tockteamSkin??null}));
  if(geometry.width!==1512||geometry.height!==949||geometry.dpr!==2||geometry.colorScheme!=='dark'||geometry.skin!==null||geometry.bodySkin!==null||errors.length) throw Error('Geometry/theme/errors check failed');
  return {url:page.url(),labels,metrics,keyboard:{first,last,copySubmenu:true,linkedSubmenu:true,escapeFocus:true},boxes,fixtureSetup:'Existing empty Study group seeded before UI actions',created,edited,afterCancel,removed,reloadStatus:response.status(),geometry,pageErrors:errors,screenshots:['/tmp/tutor-pr-menu-dark.png','/tmp/tutor-pr-bookmark-dark.png']};
}
