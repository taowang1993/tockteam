// Use playwright-cli run-code on an owned extended_display Electron endpoint only.
// Fresh isolated vault: Original.md, Clicked.md, Destination.md and Folder/.
// Never exercise default-app/Finder effects through this harness.
async page => {
  const errors = [], checks = []
  const check = (value, name) => { if (!value) throw Error(name); checks.push(name) }
  page.on('pageerror', error => errors.push(error.message))
  const cdp = await page.context().newCDPSession(page)
  try {
    await cdp.send('Emulation.setDeviceMetricsOverride', { width: 1512, height: 949, deviceScaleFactor: 2, mobile: false })
    const notice = page.getByRole('dialog', { name: 'Internal Testing Notice' })
    if (await notice.isVisible()) await notice.getByRole('button', { name: 'Continue', exact: true }).click()
    await page.getByRole('button', { name: 'TockTutor', exact: true }).click()
    const row = path => page.getByRole('button', { name: path, exact: true })
    await row('Original.md').click()
    await page.getByRole('button', { name: 'More Note Actions' }).click()
    await page.getByRole('menuitemcheckbox', { name: 'Source Mode' }).click()
    await page.locator('.cm-content').fill('# Original\n\nUNSAVED ORIGINAL\n')
    const menu = page.getByRole('menu', { name: 'Note Actions', exact: true })
    const choose = async (path, action) => {
      await row(path).click({ button: 'right' })
      await menu.getByRole('menuitem', { name: action, exact: true }).click()
    }
    const draftRetained = async name => check((await page.locator('[data-pane-id]').first().innerText()).includes('UNSAVED ORIGINAL'), name)
    await row('Clicked.md').click({ button: 'right' })
    await menu.waitFor()
    check(await menu.getByRole('menuitem').count() === 13, '13 top-level actions')
    await draftRetained('opening the menu does not navigate')
    await page.keyboard.press('Escape')
    await menu.waitFor({ state: 'hidden' })
    check(await row('Clicked.md').evaluate(el => el === document.activeElement), 'Escape restores row focus')
    await row('Clicked.md').press('Shift+F10')
    await menu.getByRole('menuitem', { name: 'Open to the Right', exact: true }).click()
    await page.locator('[data-pane-id]').nth(1).waitFor()
    check(await page.locator('[data-pane-id]').count() === 2, 'persistent right split')
    await draftRetained('split retains original draft')
    await choose('Clicked.md', 'Duplicate')
    await row('Clicked Copy.md').waitFor()
    await draftRetained('duplicate retains original draft')
    await choose('Clicked.md', 'Rename Note…')
    const rename = page.getByRole('dialog', { name: 'Rename Note', exact: true })
    await rename.getByRole('textbox').fill('Renamed')
    await rename.getByRole('button', { name: 'Rename Note', exact: true }).click()
    await rename.waitFor({ state: 'hidden' })
    await row('Renamed.md').waitFor()
    await draftRetained('rename retains original draft')
    await choose('Renamed.md', 'File Recovery')
    await page.getByRole('heading', { name: 'File Recovery', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Close Utility Panel', exact: true }).click()
    await choose('Renamed.md', 'Bookmark Note…')
    const bookmark = page.getByRole('dialog', { name: 'Bookmark Note', exact: true })
    await bookmark.getByRole('button', { name: 'Save', exact: true }).click()
    await bookmark.waitFor({ state: 'hidden' })
    await row('Renamed.md').click({ button: 'right' })
    check(await menu.getByRole('menuitem', { name: 'Edit Bookmark…', exact: true }).count() === 1, 'bookmark is bound to the clicked note')
    await menu.getByRole('menuitem', { name: 'Move Note…', exact: true }).click()
    const move = page.getByRole('dialog', { name: 'Move Note', exact: true })
    await move.getByRole('textbox').fill('Folder')
    await move.getByRole('button', { name: 'Move Note', exact: true }).click()
    await move.waitFor({ state: 'hidden' })
    await row('Folder/Renamed.md').waitFor()
    await choose('Folder/Renamed.md', 'Move File to Trash')
    await row('Folder/Renamed.md').waitFor({ state: 'hidden' })
    await draftRetained('move and trash retain original draft')
    await row('Clicked Copy.md').click({ button: 'right' })
    const state = await page.evaluate(() => ({ route: location.pathname, geometry: [innerWidth, innerHeight, devicePixelRatio], colorScheme: document.documentElement.style.colorScheme, htmlSkin: document.documentElement.dataset.tockteamSkin ?? null, bodySkin: document.body.dataset.tockteamSkin ?? null }))
    check(state.colorScheme === 'dark' && state.htmlSkin === null && state.bodySkin === null, 'explicit canonical dark appearance')
    const box = await menu.boundingBox()
    check(box.x >= 40 && box.y >= 48 && box.x + box.width <= 1512 && box.y + box.height <= 949, 'menu fits the owning route')
    check(errors.length === 0, 'no runtime errors')
    return { state, checks, errors, screenshot: (await cdp.send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false })).data }
  } finally { await cdp.detach() }
}
