import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { admitTrustedRaycastArtifact } from '../src/trusted-raycast-artifact-admission.ts'
import { trustedRaycastDescriptors } from '../src/trusted-raycast-descriptors.ts'
import { decodeTrustedRaycastCanIUseData } from '../src/trusted-raycast-can-i-use-assets.ts'
import { trustedRaycastTarPath } from './trusted-raycast-build.mjs'

// Inert reviewed data only. Never imports an extension or its dependencies.
export function trustedRaycastSettingsCatalogSource() {
  const vendor = fileURLToPath(new URL('../plugins/trusted-raycast/vendor/', import.meta.url))
  const descriptor = trustedRaycastDescriptors['google-translate']
  const bytes = admitTrustedRaycastArtifact(descriptor, `${vendor}/google-translate.tar`)
  const source = execFileSync(trustedRaycastTarPath(), ['-xOf', '-', `${descriptor.artifactRoot}/source/vendor/@iamtraction-translate/src/languages.ts`], { input: bytes, timeout: 15000, maxBuffer: 1024 * 1024 }).toString('utf8')
  const literal = /export const languages = (\{[\s\S]*?\}) as const;/u.exec(source)?.[1]
  if (!literal) throw new Error('Pinned language data is unavailable')
  const languages = JSON.parse(literal.replace(/,\s*\}/u, '}'))
  if (!Object.entries(languages).every(([code, label]) => /^[A-Za-z-]{2,16}$/u.test(code) && typeof label === 'string' && label.length <= 100)) throw new Error('Invalid pinned language data')
  const data = decodeTrustedRaycastCanIUseData(readFileSync(`${vendor}/can-i-use-data.json.gz`))
  return `/** Generated by scripts/trusted-raycast-settings-catalog.mjs from admitted inert data.\n * Attribution: plugins/trusted-raycast/vendor and its bundled third-party notices. */\nexport const TRANSLATE_SETTINGS_LANGUAGES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(languages, null, 2)})\nexport const CAN_I_USE_SETTINGS_TARGETS: readonly string[] = Object.freeze(${JSON.stringify(data.canonicalTargets)})\nexport const CAN_I_USE_SETTINGS_DEFAULT_TARGETS: readonly string[] = Object.freeze(${JSON.stringify(data.defaultTargets)})\n`
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = fileURLToPath(new URL('../src/trusted-raycast-settings-catalog.ts', import.meta.url))
  const source = trustedRaycastSettingsCatalogSource()
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== source) throw new Error('Regenerate the trusted extension settings catalog')
  } else writeFileSync(path, source)
}
